 provider VARCHAR(24) NOT NULL,
 provider_event_id VARCHAR(128) NOT NULL,
 event_type VARCHAR(80) NOT NULL,
 payload_sha256 CHAR(64) NOT NULL,
 payment_attempt_id CHAR(36) NULL,
 processing_result VARCHAR(24) NOT NULL DEFAULT 'processed',
 received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 processed_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY (id),
 UNIQUE KEY payment_webhook_provider_event_uq (provider, provider_event_id),
 KEY payment_webhook_attempt_received_idx (payment_attempt_id, received_at),
