-- Phase 8: sandbox-only payment attempts, verified webhook receipts and idempotent refunds.
CREATE TABLE IF NOT EXISTS payment_attempts (
 id CHAR(36) NOT NULL,
 order_id CHAR(36) NOT NULL,
 provider VARCHAR(24) NOT NULL,
 idempotency_key CHAR(36) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 provider_receipt VARCHAR(40) NOT NULL,
 provider_order_id VARCHAR(64) NULL,
 provider_payment_id VARCHAR(64) NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'creating',
 amount_minor BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL,
 failure_code VARCHAR(80) NULL,
 authorized_at DATETIME(3) NULL,
 captured_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 PRIMARY KEY (id),
 UNIQUE KEY payment_attempts_order_key_uq (order_id, idempotency_key),
 UNIQUE KEY payment_attempts_provider_receipt_uq (provider, provider_receipt),
 UNIQUE KEY payment_attempts_provider_order_uq (provider, provider_order_id),
 UNIQUE KEY payment_attempts_provider_payment_uq (provider, provider_payment_id),
 KEY payment_attempts_order_status_idx (order_id, status, created_at),
 CONSTRAINT payment_attempts_order_fk FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT payment_attempts_provider_check CHECK (provider = 'razorpay'),
 CONSTRAINT payment_attempts_status_check CHECK (status IN ('creating','creation_unknown','created','authorized','captured','failed','captured_after_expiry')),
 CONSTRAINT payment_attempts_amount_check CHECK (amount_minor > 0),
 CONSTRAINT payment_attempts_currency_check CHECK (currency REGEXP '^[A-Z]{3}$'),
 CONSTRAINT payment_attempts_hash_check CHECK (request_hash REGEXP '^[a-f0-9]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
