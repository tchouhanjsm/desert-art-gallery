CREATE TABLE IF NOT EXISTS payment_refunds (
 id CHAR(36) NOT NULL,
 payment_attempt_id CHAR(36) NOT NULL,
 order_id CHAR(36) NOT NULL,
 provider VARCHAR(24) NOT NULL,
 idempotency_key VARCHAR(40) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 provider_refund_id VARCHAR(64) NULL,
 amount_minor BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'requested',
 reason VARCHAR(500) NOT NULL,
 requested_by CHAR(36) NOT NULL,
 failure_code VARCHAR(80) NULL,
 processed_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 PRIMARY KEY (id),
 UNIQUE KEY payment_refunds_provider_key_uq (provider, idempotency_key),
 UNIQUE KEY payment_refunds_provider_id_uq (provider, provider_refund_id),
 KEY payment_refunds_order_status_idx (order_id, status, created_at),
 KEY payment_refunds_attempt_status_idx (payment_attempt_id, status),
 CONSTRAINT payment_refunds_attempt_fk FOREIGN KEY (payment_attempt_id) REFERENCES payment_attempts(id) ON DELETE RESTRICT,
 CONSTRAINT payment_refunds_order_fk FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT payment_refunds_provider_check CHECK (provider = 'razorpay'),
 CONSTRAINT payment_refunds_status_check CHECK (status IN ('requested','pending','processed','failed','unknown')),
 CONSTRAINT payment_refunds_amount_check CHECK (amount_minor > 0),
 CONSTRAINT payment_refunds_currency_check CHECK (currency REGEXP '^[A-Z]{3}$'),
 CONSTRAINT payment_refunds_hash_check CHECK (request_hash REGEXP '^[a-f0-9]{64}$'),
 CONSTRAINT payment_refunds_reason_check CHECK (CHAR_LENGTH(TRIM(reason)) BETWEEN 1 AND 500)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
